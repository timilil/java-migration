package com.example.config;

import org.hibernate.dialect.H2Dialect;
import org.hibernate.dialect.identity.IdentityColumnSupport;
import org.hibernate.dialect.identity.IdentityColumnSupportImpl;

/**
 * H2 dialect that generates an identity-insert SQL fragment compatible with
 * H2's newer versions, which reject an explicit NULL value for identity
 * columns and instead require the DEFAULT keyword.
 */
public class H2CompatibleDialect extends H2Dialect {

    @Override
    public String toBooleanValueString(boolean bool) {
        return bool ? "true" : "false";
    }

    @Override
    public IdentityColumnSupport getIdentityColumnSupport() {
        return new IdentityColumnSupportImpl() {
            @Override
            public boolean supportsIdentityColumns() {
                return true;
            }

            @Override
            public String getIdentityColumnString(int type) {
                return "generated by default as identity";
            }

            @Override
            public String getIdentitySelectString(String table, String column, int type) {
                return "call identity()";
            }

            @Override
            public String getIdentityInsertString() {
                return "default";
            }
        };
    }
}
